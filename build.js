#!/usr/bin/env node
/* ============================================================================
 * Cute Animals — production build.
 * Concatenates the game's plain (non-module) scripts IN LOAD ORDER into a single
 * file, then minifies it with esbuild (via npx; no local node_modules needed).
 * If esbuild is unavailable it still writes a working concatenated bundle.
 *
 *   node build.js   ->   writes bundle.min.js
 *
 * index.html loads bundle.min.js in PRODUCTION and the individual js/*.js files
 * on localhost (so dev keeps instant edits with no rebuild). Re-run before each
 * deploy so the bundle matches the sources.
 * ==========================================================================*/
'use strict';
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// keep in sync with index.html's <script> load order
const FILES = [
  'contract','i18n','maps','weather','species','classes','terrain','entities','weapons','voxel-theme',
  'hazards','fx','voices','ai','modes','meta','account','entitlement','ads','net','share','challenge','clans','ranked','screens','ui','portal','perf-tier','postfx','core','intro','puzzles','menu','menu-editor','menu-lobby','menu-profile','menu-achievements','menu-leaderboard','menu-challenge','menu-clan','menu-ranked','menu-puzzles','menu-credits','menu-teamedit','menu-skilltree','menu-account','menu-daily','menu-shop','menu-battlepass','menu-gauntlet','menu-help','menu-contact'
].map(n => path.join(__dirname, 'js', n + '.js'));

const OUT = path.join(__dirname, 'bundle.min.js');
const TMP = path.join(__dirname, '.bundle.tmp.js');

let concat = '/* Block & Destroy bundle — generated by build.js, do not edit */\n';
for (const f of FILES) {
  if (!fs.existsSync(f)) { console.error('MISSING:', f); process.exit(1); }
  concat += '\n;/* ' + path.basename(f) + ' */\n' + fs.readFileSync(f, 'utf8') + '\n';
}
fs.writeFileSync(TMP, concat);

let minified = null;
try {
  // esbuild via npx (cached in ~/.npm; no node_modules in the deployed tree)
  execSync('npx --yes esbuild@0.21.5 ' + JSON.stringify(TMP) +
           ' --minify --target=es2018 --legal-comments=none --outfile=' + JSON.stringify(OUT),
           { stdio: ['ignore','ignore','inherit'] });
  minified = fs.readFileSync(OUT, 'utf8');
} catch (e) {
  console.warn('esbuild unavailable — writing unminified concatenated bundle.');
  minified = concat.trimEnd() + '\n';
  fs.writeFileSync(OUT, minified);
}
fs.unlinkSync(TMP);

const kb = (n) => (n/1024).toFixed(1) + ' KB';
const srcBytes = concat.length, outBytes = minified.length;
console.log('bundle.min.js written:', kb(outBytes), '(from', FILES.length, 'files,', kb(srcBytes), 'source)');

/* ----------------------------------------------------------------------------
 * i18n DRIFT-GATE (QA backlog #4): a fordítatlan-kulcs drift 3× előfordult már
 * (új string bekerült az EN-be, de a lazy szótárakból kimaradt → ES/PT/ZH/DE
 * angolul jelent meg). Build-időben összevetjük: minden addEN(...) kulcsnak
 * benne KELL lennie minden js/i18n-<lang>.js szótárban. Csak FIGYELMEZTET (nem
 * bukik), hogy egy él-deploy soha ne akadjon el rajta — de a drift látszik.
 * -------------------------------------------------------------------------- */
try {
  // 1) gyűjtsd az ÖSSZES addEN(...) kulcsot minden forrás-js-ből
  const enKeys = new Set();
  const keyRe = /["']((?:[^"'\\]|\\.)*)["']\s*:/g;
  function collectAddEN(src){
    // minden addEN( ... ) blokk kulcsai (a kulcs a kettőspont előtti string)
    const re = /addEN\s*\(\s*\{/g; let m;
    while ((m = re.exec(src))){
      // a { utáni objektum-literál a párosító } -ig
      let i = re.lastIndex - 1, depth = 0, end = -1;
      for (let j = i; j < src.length; j++){
        const c = src[j];
        if (c === '{') depth++;
        else if (c === '}'){ depth--; if (depth === 0){ end = j; break; } }
      }
      if (end < 0) continue;
      const body = src.slice(i, end);
      let km; keyRe.lastIndex = 0;
      while ((km = keyRe.exec(body))) enKeys.add(km[1]);
    }
  }
  const jsDir = path.join(__dirname, 'js');
  for (const f of fs.readdirSync(jsDir)){
    if (!f.endsWith('.js') || f.startsWith('i18n-')) continue;
    try { collectAddEN(fs.readFileSync(path.join(jsDir, f), 'utf8')); } catch(e){}
  }
  // 2) minden lazy szótárból gyűjtsd a meglévő kulcsokat, és diffeld
  const langFiles = fs.readdirSync(jsDir).filter(f => /^i18n-[a-z]{2}\.js$/.test(f));
  let totalMissing = 0;
  for (const lf of langFiles){
    const src = fs.readFileSync(path.join(jsDir, lf), 'utf8');
    const have = new Set(); let km; keyRe.lastIndex = 0;
    while ((km = keyRe.exec(src))) have.add(km[1]);
    const missing = [];
    enKeys.forEach(k => { if (!have.has(k)) missing.push(k); });
    if (missing.length){
      totalMissing += missing.length;
      console.warn('  ⚠ i18n-DRIFT ' + lf + ': ' + missing.length + ' hiányzó kulcs, pl.: ' +
                   missing.slice(0, 4).map(s => JSON.stringify(s)).join(', '));
    }
  }
  if (totalMissing === 0 && langFiles.length){
    console.log('i18n drift-gate: OK (' + enKeys.size + ' EN kulcs, ' + langFiles.length + ' szótár szinkronban)');
  }
} catch(e){ /* a drift-gate SOHA ne buktassa a buildet */ }
